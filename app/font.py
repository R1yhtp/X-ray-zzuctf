FONT = {ch:tuple(int(x,16) for x in rows.split()) for ch,rows in PATTERNS.items()}
assert len(set(FONT.values())) == len(FONT)

def layout(row, col):
    return ((row//8)*12 + (11-col if (row//8)&1 else col))*8 + row%8

def rasterize(text):
    pixels = [[0]*192 for _ in range(64)]
    for index,ch in enumerate(text):
        left=6+(index%30)*6
        top=14+(index//30)*10
        for y,bits in enumerate(FONT[ch]):
            for x in range(5):
                pixels[top+y][left+x]=(bits>>(4-x))&1
    words=[0]*768
    for y in range(64):
        for col in range(12):
            words[layout(y,col)]=sum(pixels[y][16*col+b]<<b for b in range(16))
    return words
